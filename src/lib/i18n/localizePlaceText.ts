type LocaleBag = {
  ko: string;
  en: string;
  ja: string;
  "zh-CN": string;
  vi: string;
  es: string;
  de: string;
  fr: string;
};

function applyTerms(
  text: string,
  locale: SupportedLocale,
  terms: LocaleBag[],
): string {
  let result = text;
  for (const term of terms) {
    if (!result.includes(term.ko)) continue;
    const replacement = term[locale] ?? term.en;
    result = result.split(term.ko).join(replacement);
  }
  return result;
}

export function localizePlaceText(
  text: string | null | undefined,
  locale: SupportedLocale,
): string {
  if (!text) return "";
  if (locale === "ko") return text;
  const withPhrases = applyTerms(text, locale, CONTENT_PHRASES);
  const placeTerms = [...PLACE_TERMS].sort((a, b) => b.ko.length - a.ko.length);
  return applyTerms(withPhrases, locale, placeTerms);
}
